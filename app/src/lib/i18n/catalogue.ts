export type CleLibelle = keyof typeof LIBELLES;

/** Une variable de libellé peut être un LIBELLÉ : « {étape} : 3 {quoi} » est
 *  fait de deux entrées du catalogue et d'un nombre. Sans cette récursion, une
 *  phrase composée porterait la clé brute à l'écran. */
export type Variable = string | number | { cle: CleLibelle };

/** Le libellé, dans la locale demandée, avec ses variables. */
export function traduire(locale: Locale, cle: CleLibelle, vars: Record<string, Variable> = {}): string {
  const e = (LIBELLES as Record<string, Entree>)[cle];
  /* UNE CLÉ INCONNUE NE PLANTE PAS L'ÉCRAN — elle se dénonce. Un `[cle][locale]`
     sur `undefined` rendait une page 500 pleine, sans dire laquelle ni pourquoi :
     un refus rendu en page 500 est le silence que la règle 13 nomme. */
  if (!e) return `⟨${cle}⟩`;
  return e[locale].replace(/\{(\w+)\}/g, (m, k) => {
    if (!(k in vars)) return m;
    const v = vars[k];
    return typeof v === 'object' && v !== null && 'cle' in v ? traduire(locale, v.cle) : String(v);
  });
}
